"use strict";

// Shared trust roots for the public Linux and Windows LLVM 21 source SDK producers.
const fs = require("node:fs"), path = require("node:path"), {spawnSync} = require("node:child_process");
const {createHash} = require("node:crypto"), {fileHash} = require("./build-source-inputs");

const archiveName = "llvm-project-21.1.8.src.tar.xz";
const archiveSha256 = "4633a23617fa31a3ea51242586ea7fb1da7140e426bd62fc164261fe036aa142";
const tarTool = "/usr/bin/tar";
const sourceDirectories = Object.freeze(["llvm", "clang", "lld", "cmake", "third-party", "libunwind/include"]);

/** @param {unknown} value @returns {value is string} */
const literal = value => typeof value === "string" && value.length > 0 && value.length <= 4096 && path.isAbsolute(value) &&
  !/[;"'$`\\\r\n\0]/.test(value) && !Array.from(value).some(char => char.charCodeAt(0) < 32 || char.charCodeAt(0) === 127);

/** CMake bracket arguments preserve literal paths without evaluating their contents. @param {string} value */
function cmakeBracketArgument(value) {
  let equals = "";
  while (value.includes("]" + equals + "]")) {equals += "=";}
  return "[" + equals + "[" + value + "]" + equals + "]";
}

/** Generate a deferred source-scoped host option shim outside the upstream source tree. @param {string} source */
function llvmAmdgpulibCallsCompileOptionsShim(source) {
  if (!literal(source) || path.normalize(source) !== source) {throw new Error("Select a canonical absolute LLVM source root");}
  const file = path.join(source, "llvm", "lib", "Target", "AMDGPU", "AMDGPULibCalls.cpp"), directory = path.dirname(file);
  return ["# Generated by the MoM LLVM 21 SDK producer; do not edit.",
    "function(_mom_llvm_amdgpulibcalls_host_option)",
    "  set_property(SOURCE " + cmakeBracketArgument(file) + " DIRECTORY " + cmakeBracketArgument(directory) +
      " APPEND PROPERTY COMPILE_OPTIONS " + cmakeBracketArgument("-fno-builtin") + ")",
    "endfunction()", "cmake_language(DEFER CALL _mom_llvm_amdgpulibcalls_host_option)", ""].join("\n");
}

/** CMAKE_PROJECT_TOP_LEVEL_INCLUDES requires CMake 3.24+. @param {string} version */
function verifyCmakeVersion(version) {
  const match = version.match(/(?:^|\n)cmake version (\d+)\.(\d+)(?:\.(\d+))?(?:\s|$)/);
  if (!match || Number(match[1]) < 3 || Number(match[1]) === 3 && Number(match[2]) < 24) {
    throw new Error("Linux LLVM 21 SDK requires CMake 3.24 or newer");
  }
}

/** Hash the exact consumed LLVM/Clang/LLD source trees and libunwind headers, including membership and symlink text.
 * @param {string} source @returns {{sha256: string, files: number, bytes: number}} */
function llvmSourceSnapshot(source) {
  if (!literal(source)) {throw new Error("Select an absolute LLVM 21 source root");}
  const root = fs.realpathSync(source), hash = createHash("sha256"); let files = 0, bytes = 0;
  /** @param {string} directory */
  function visit(directory) {
    for (const entry of fs.readdirSync(directory, {withFileTypes: true}).sort((a, b) => a.name.localeCompare(b.name))) {
      const file = path.join(directory, entry.name), relative = path.relative(root, file).split(path.sep).join("/");
      if (++files > 200000 || relative.length > 4096 || /[\r\n\0]/.test(relative)) {throw new Error("LLVM 21 source inventory exceeds bounds");}
      if (entry.isDirectory()) {visit(file); continue;}
      if (entry.isSymbolicLink()) {
        const link = fs.readlinkSync(file);
        if (link.length > 4096 || /[\r\n\0]/.test(link)) {throw new Error("Invalid LLVM 21 source link");}
        bytes += Buffer.byteLength(link); hash.update("link\0" + relative + "\0" + link + "\n");
      } else if (entry.isFile()) {
        const digest = fileHash(file), size = fs.statSync(file).size;
        if ((bytes += size) > (8 * 1024 * 1024 * 1024)) {throw new Error("LLVM 21 source inventory exceeds byte limit");}
        hash.update("file\0" + relative + "\0" + size + "\0" + digest + "\n");
      } else {throw new Error("LLVM 21 source contains a non-file input: " + relative);}
    }
  }
  for (const name of sourceDirectories) {
    const directory = path.join(root, name);
    const stat = fs.lstatSync(directory, {throwIfNoEntry: false});
    if (!stat?.isDirectory()) {throw new Error("Missing original LLVM 21 source directory: " + name);}
    visit(directory);
  }
  const top = path.join(root, "LICENSE.TXT");
  const topHash = fileHash(top); hash.update("file\0LICENSE.TXT\0" + fs.statSync(top).size + "\0" + topHash + "\n");
  return {sha256: hash.digest("hex"), files, bytes};
}

/** Inspect the pinned archive catalog before extracting only build-required upstream roots.
 * @param {string} archive */
function verifyArchiveCatalog(archive) {
  const result = spawnSync(tarTool, ["-tf", archive, "--quoting-style=literal"], {encoding: "utf8", timeout: 600000, maxBuffer: 64 << 20});
  if (result.error || result.signal || result.status !== 0 || typeof result.stdout !== "string" || /[\0]/.test(result.stdout)) {
    throw new Error("Pinned LLVM 21 source archive catalog could not be verified", {cause: result.error});
  }
  const prefix = "llvm-project-21.1.8.src/", entries = result.stdout.split("\n").filter(Boolean), seen = new Set();
  if (!entries.length || entries.length > 250000) {throw new Error("Pinned LLVM 21 archive member count is invalid");}
  for (const member of entries) {
    if (member.length > 4096 || /[\r\n\0]/.test(member) || !member.startsWith(prefix) || member.startsWith("/") ||
        member.split("/").some(part => part === ".." || part === ".")) {throw new Error("Unsafe LLVM 21 archive member path");}
    if (seen.has(member)) {throw new Error("Duplicate LLVM 21 archive member");}
    seen.add(member);
  }
  for (const name of [...sourceDirectories, "LICENSE.TXT"]) {
    const selected = prefix + name + (sourceDirectories.includes(name) ? "/" : "");
    if (!seen.has(selected)) {throw new Error("Pinned LLVM 21 archive omitted required source: " + name);}
  }
  return {members: entries.length, sha256: createHash("sha256").update(entries.join("\n") + "\n").digest("hex")};
}

module.exports = {archiveName, archiveSha256, tarTool, sourceDirectories, llvmSourceSnapshot, verifyArchiveCatalog,
  llvmAmdgpulibCallsCompileOptionsShim, verifyCmakeVersion};
