"use strict";

// Prepare only explicit Windows cross-build inputs. Original Clang/LLVM drivers handle
// compilation, archiving and MASM; no compiler wrapper or generated algorithm is needed.
const fs = require("node:fs"), path = require("node:path");
const {validateWindowsLlvmSdkConfig, validateWindowsControllerConfig, vfsFiles} = require("./build-native-windows-controller");
const {hasExactBuildFields, buildFileInputs, fileHash, readBuildJson} = require("./build-source-inputs");
const repo = path.resolve(__dirname, "..");
/** @param {string} p */
const literal = p => path.isAbsolute(p) && p.length <= 4096 && !/[;"$\\]/.test(p) &&
  !Array.from(p).some(c => c.charCodeAt(0) < 32 || c.charCodeAt(0) === 127) && !p.includes("]==]");
/** @param {string} value */
const cmake = value => "[==[" + value + "]==]";

/** The LLVM descriptor producer emits exactly this reduced shape; all other inputs retain the
 * strict full-controller validation used by existing callers. @param {unknown} value */
function validateWindowsJitDescriptor(value) {
  if (value && typeof value === "object" && !Array.isArray(value) &&
      hasExactBuildFields(value, ["tools", "version", "windowsSdk"])) {
    return validateWindowsLlvmSdkConfig(value);
  }
  return validateWindowsControllerConfig(value);
}

/** Apply the workaround only to LLVM's HeatUtils translation unit when the selected
 * host compiler is IntelLLVM on Windows. The no-builtin option avoids Intel vector-math
 * helpers escaping this one static compiler object into the final MSVC-ABI link. */
const heatUtilsSourceOptions = `# Generated by the MoM Windows JIT toolchain producer; do not edit.
function(_mom_windows_jit_heatutils_host_option)
  get_property(_mom_in_try_compile GLOBAL PROPERTY IN_TRY_COMPILE)
  if(_mom_in_try_compile)
    return()
  endif()
  if(NOT WIN32 OR NOT CMAKE_CXX_COMPILER_ID STREQUAL "IntelLLVM")
    return()
  endif()
  set(_mom_heatutils_source "\${CMAKE_SOURCE_DIR}/lib/Analysis/HeatUtils.cpp")
  if(NOT EXISTS "\${_mom_heatutils_source}")
    message(FATAL_ERROR "Windows IntelLLVM JIT source is missing lib/Analysis/HeatUtils.cpp")
  endif()
  set_property(SOURCE "\${_mom_heatutils_source}" DIRECTORY "\${CMAKE_SOURCE_DIR}/lib/Analysis" APPEND PROPERTY COMPILE_OPTIONS ${cmake("-fno-builtin")})
endfunction()
cmake_language(DEFER CALL _mom_windows_jit_heatutils_host_option)
`;

/** CMake 3.28 loads this after Windows-IntelLLVM's driver rules and before ABI probes.
 * Keep real compiler-ID/ABI probes, but send target links and archives to the selected
 * MSVC-ABI tools instead of asking icx-cl to forward LLD-only flags. Explicit source
 * operands are opt-in for JIT consumers whose POSIX source paths need disambiguation.
 * @param {string} linkerFlags @param {string[]} runtimeLibraries @param {boolean} [explicitSourceOperands] */
function windowsIntelRuleOverride(linkerFlags, runtimeLibraries, explicitSourceOperands = false) {
  if (typeof explicitSourceOperands !== "boolean") {throw new Error("Intel Windows source operands must be selected explicitly");}
  const hasControl = typeof linkerFlags === "string" && Array.from(linkerFlags).some(c => c.charCodeAt(0) < 32 || c.charCodeAt(0) === 127);
  if (typeof linkerFlags !== "string" || linkerFlags.length > 65536 || /[;$`\\]/.test(linkerFlags) || hasControl ||
      linkerFlags.includes("]==]")) {
    throw new Error("Intel Windows linker rules need literal flags and bounded library names");
  }
  if (!Array.isArray(runtimeLibraries) || runtimeLibraries.length > 512 ||
      !runtimeLibraries.every(file => typeof file === "string" && literal(file))) {
    throw new Error("Intel Windows linker rules need literal flags and bounded library names");
  }
  if (runtimeLibraries.some(file => !/^[A-Za-z0-9_.-]+\.lib$/i.test(path.basename(file)))) {
    throw new Error("Intel Windows linker rules need literal flags and bounded library names");
  }
  // Linux is case-sensitive. Bind exact CRT/OS archives in the link rule itself: CMake
  // deliberately clears standard libraries during ABI detection, but it still needs the CRT.
  const libraries = runtimeLibraries.map(file => '"' + file + '"').join(" ");
  const cLink = "<CMAKE_LINKER> /NOLOGO /out:<TARGET> /MACHINE:X64 <OBJECTS> <CMAKE_C_LINK_FLAGS> <LINK_FLAGS> <LINK_LIBRARIES> " + libraries + " /SUBSYSTEM:CONSOLE";
  const cxxLink = cLink.replace("<CMAKE_C_LINK_FLAGS>", "<CMAKE_CXX_LINK_FLAGS>");
  const createArchive = "<CMAKE_AR> /NOLOGO /out:<TARGET> <LINK_FLAGS> <OBJECTS>";
  return [
    // The runtime SDK shares this hook with the compiler SDK. Leave Clang's platform
    // rules unchanged; do not infer the compiler's identity from its filename.
    'if(NOT CMAKE_C_COMPILER_ID STREQUAL "IntelLLVM" AND NOT CMAKE_CXX_COMPILER_ID STREQUAL "IntelLLVM")',
    "  return()",
    "endif()",
    ...(explicitSourceOperands ? [
      // Some JIT builds use POSIX /w... source paths, which icx-cl can parse as warning switches.
      ...[["C", "c"], ["CXX", "p"]].flatMap(([language, kind]) => [
        `if(CMAKE_${language}_COMPILER_ID STREQUAL "IntelLLVM" AND DEFINED CMAKE_${language}_COMPILE_OBJECT)`,
        `  if(NOT CMAKE_${language}_COMPILE_OBJECT MATCHES "/T${kind}<SOURCE>")`,
        `    string(REPLACE "<SOURCE>" "/T${kind}<SOURCE>" CMAKE_${language}_COMPILE_OBJECT "\${CMAKE_${language}_COMPILE_OBJECT}")`,
        "  endif()",
        "endif()",
      ]),
    ] : []),
    // Windows-IntelLLVM wraps MSVC linker flags in /Qoption,link,. These rules invoke
    // LLD/llvm-lib directly, so discard that driver-only wrapping and archiver flags.
    `set(CMAKE_EXE_LINKER_FLAGS_INIT ${cmake(linkerFlags)})`,
    `set(CMAKE_EXE_LINKER_FLAGS_DEBUG_INIT ${cmake("/DEBUG")})`,
    `set(CMAKE_EXE_LINKER_FLAGS_RELWITHDEBINFO_INIT ${cmake("/DEBUG")})`,
    `set(CMAKE_EXE_LINKER_FLAGS_MINSIZEREL_INIT ${cmake("")})`,
    `set(CMAKE_EXE_LINKER_FLAGS_RELEASE_INIT ${cmake("")})`,
    `set(CMAKE_STATIC_LINKER_FLAGS_INIT ${cmake("")})`,
    `set(CMAKE_C_LINKER_WRAPPER_FLAG ${cmake("")})`,
    `set(CMAKE_C_LINKER_WRAPPER_FLAG_SEP ${cmake("")})`,
    `set(CMAKE_CXX_LINKER_WRAPPER_FLAG ${cmake("")})`,
    `set(CMAKE_CXX_LINKER_WRAPPER_FLAG_SEP ${cmake("")})`,
    `set(CMAKE_C_CREATE_CONSOLE_EXE ${cmake("")})`,
    `set(CMAKE_CXX_CREATE_CONSOLE_EXE ${cmake("")})`,
    ...["C", "CXX"].map(language => `set(CMAKE_${language}_STANDARD_LIBRARIES_INIT ${cmake("")})`),
    `set(CMAKE_C_LINK_EXECUTABLE ${cmake(cLink)})`,
    `set(CMAKE_CXX_LINK_EXECUTABLE ${cmake(cxxLink)})`,
    `set(CMAKE_C_CREATE_STATIC_LIBRARY ${cmake(createArchive)})`,
    `set(CMAKE_CXX_CREATE_STATIC_LIBRARY ${cmake(createArchive)})`,
    "",
  ].join("\n");
}

/** Reuse the application's OS SDK descriptor, not a second SDK/header policy. Clang's own
 * resource headers must precede MSVC's intrinsics declarations; GNU device-JIT resources
 * are supplied separately to the original compiler graph.
 * @param {unknown} descriptor @param {string} sdk @param {string} nativeTools @param {string} output
 * @param {unknown} [hostCompilers] */
function windowsJitToolchainPlan(descriptor, sdk, nativeTools, output, hostCompilers) {
  const config = validateWindowsJitDescriptor(descriptor), {windowsSdk, tools} = config, bin = path.dirname(tools.lldLink);
  const host = /** @type {{cc: string, cxx: string} | undefined} */ (hostCompilers);
  if (hostCompilers !== undefined && (!host || !hasExactBuildFields(host, ["cc", "cxx"]) ||
      ![host.cc, host.cxx, tools.clangResourceInclude].every(file => typeof file === "string" && literal(file)))) {
    throw new Error("Windows JIT host compilers must be a paired literal C/C++ selection");
  }
  // The CI caller has already resolved and version-checked this canonical Intel 2026.2
  // compiler. Other explicit host pairs (notably clang-cl) must keep CMake's manifest path.
  const intelHost = !!host && host.cc === host.cxx && path.basename(host.cc).toLowerCase() === "icx-cl";
  if (![sdk, nativeTools, output, tools.lldLink, windowsSdk.overlay, windowsSdk.sourceRoot, ...windowsSdk.includeRoots, ...windowsSdk.libraryRoots].every(literal)) {
    throw new Error("Select literal absolute Windows JIT toolchain paths");
  }
  const aliases = path.join(output, "bin"), libraries = path.join(output, "lib"), overlay = path.join(output, "vfs.json"),
    sourceOptionsFile = path.join(output, "heatutils-source-options.cmake");
  const compilerTools = {CMAKE_C_COMPILER: host?.cc || path.join(sdk, "bin/clang-cl"), CMAKE_CXX_COMPILER: host?.cxx || path.join(sdk, "bin/clang-cl"),
    CMAKE_AR: path.join(aliases, "llvm-lib"), CMAKE_RANLIB: path.join(aliases, "llvm-ranlib"), CMAKE_LINKER: tools.lldLink,
    CMAKE_RC_COMPILER: path.join(bin, "llvm-rc"), ...(intelHost ? {} : {CMAKE_MT: path.join(bin, "llvm-mt")}), CMAKE_ASM_MASM_COMPILER: path.join(bin, "llvm-ml"),
    LLVM_TABLEGEN: path.join(nativeTools, "llvm-tblgen"), CLANG_TABLEGEN: path.join(nativeTools, "clang-tblgen"), LLVM_SPIRV: path.join(sdk, "bin/llvm-spirv")};
  const links = [libraries, ...windowsSdk.libraryRoots].map(root => '/libpath:"' + root + '"').join(" ") + " /INCREMENTAL:NO /machine:x64";
  // Only the verified Intel route invokes LLD directly and bypasses CMake's VS manifest wrapper.
  const ruleOverride = intelHost ? path.join(output, "intel-link-rules.cmake") : undefined;
  const ruleOverrideText = intelHost ? windowsIntelRuleOverride(links,
    [...windowsSdk.msvcLibraries, ...windowsSdk.ucrtLibraries, ...windowsSdk.importLibraries], true) : undefined;
  // Host intrinsic headers follow the selected compiler; the embedded JIT resources stay on sdk.
  const flags = ["--target=x86_64-pc-windows-msvc", "-nostdinc", "-I" + (host ? tools.clangResourceInclude : path.join(sdk, "lib/clang/23/include")),
    "-Xclang", "-ivfsoverlay", "-Xclang", overlay, ...windowsSdk.includeRoots.map(root => "-I" + root), "/MT", "/EHsc", "/Gy", "/Gw"].map(s => '"' + s + '"').join(" ");
  const toolchain = ["set(CMAKE_SYSTEM_NAME Windows)", "set(CMAKE_SYSTEM_PROCESSOR AMD64)", "set(CMAKE_SYSTEM_VERSION 10.0)",
    // LLVM's HAVE_* probes feed explicit Windows JIT symbol references, so they must
    // link against the selected CRT instead of treating any compilable declaration as present.
    "set(CMAKE_TRY_COMPILE_TARGET_TYPE EXECUTABLE)", "set(CMAKE_MSVC_RUNTIME_LIBRARY MultiThreaded)",
    `set(CMAKE_PROJECT_TOP_LEVEL_INCLUDES ${cmake(sourceOptionsFile)})`,
    ...Object.entries(compilerTools).map(([name, file]) => `set(${name} ${cmake(file)} CACHE FILEPATH "" FORCE)`),
    ...(ruleOverride ? [`set(CMAKE_USER_MAKE_RULES_OVERRIDE_C ${cmake(ruleOverride)})`,
      `set(CMAKE_USER_MAKE_RULES_OVERRIDE_CXX ${cmake(ruleOverride)})`] : []),
    "set(CMAKE_ASM_MASM_FLAGS_INIT --m64)", `set(LLVM_NATIVE_TOOL_DIR ${cmake(nativeTools)} CACHE PATH "" FORCE)`,
    `set(CMAKE_C_FLAGS_INIT ${cmake(flags)})`, `set(CMAKE_CXX_FLAGS_INIT ${cmake(flags + " /std:c++17")})`,
    `set(CMAKE_EXE_LINKER_FLAGS_INIT ${cmake(links)})`, `set(CMAKE_FIND_ROOT_PATH ${cmake(windowsSdk.sourceRoot)})`,
    ...["LIBRARY", "INCLUDE", "PACKAGE"].map(name => `set(CMAKE_FIND_ROOT_PATH_MODE_${name} ONLY)`), "set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)", ""].join("\n");
  return {config, compilerTools, aliases, libraries, overlay, sourceOptionsFile, sourceOptionsText: heatUtilsSourceOptions,
    ruleOverride, ruleOverrideText, toolchain};
}

/** Data/alias preparation only; freeze every VFS, OS archive, bootstrap and generator file
 * before the separate compiler producer starts. Existing evidence/SDK installs stay intact.
 * @param {string} descriptorFile @param {string} sdk @param {string} nativeTools @param {string} output
 * @param {NodeJS.ProcessEnv} [environment] @param {unknown} [hostCompilers] */
function prepareWindowsJitToolchain(descriptorFile, sdk, nativeTools, output, environment = process.env, hostCompilers) {
  if (process.platform !== "linux" || environment["MOM_AOT_BUILD_ONLY"] !== "1") {throw new Error("Windows JIT toolchain preparation requires Linux and MOM_AOT_BUILD_ONLY=1");}
  const plan = windowsJitToolchainPlan(readBuildJson(descriptorFile), sdk, nativeTools, output, hostCompilers), target = path.join(fs.realpathSync(path.dirname(output)), path.basename(output));
  if (target !== output || fs.existsSync(output)) {throw new Error("Select a new canonical Windows JIT toolchain output");}
  for (const root of [repo, sdk, nativeTools, plan.config.windowsSdk.sourceRoot]) {
    const relative = path.relative(fs.realpathSync(root), target);
    if (!relative || !path.isAbsolute(relative) && relative !== ".." && !relative.startsWith(".." + path.sep)) {throw new Error("Windows JIT toolchain output overlaps its inputs");}
  }
  const prefixes = plan.config.windowsSdk.includeRoots.map(root => root.toLowerCase() + path.sep);
  const virtual = [...vfsFiles(plan.config.windowsSdk.overlay)].filter(([name]) => prefixes.some(prefix => name.toLowerCase().startsWith(prefix)));
  if (!virtual.length) {throw new Error("Missing Windows JIT OS header mappings");}
  const inputs = [descriptorFile, __filename, require.resolve("./build-native-windows-controller"), require.resolve("./build-source-inputs"),
    plan.config.windowsSdk.overlay, ...virtual.map(([, file]) => file), ...Object.values(plan.compilerTools).filter(file => !file.startsWith(output + path.sep)), path.join(sdk, "bin/llvm-ar")];
  // The Linux filesystem is case-sensitive; use only explicit SDK archives, rejecting aliases
  // that would select different bytes for the same Windows library name.
  const imports = new Map();
  for (const root of plan.config.windowsSdk.libraryRoots) {
    for (const name of fs.readdirSync(root)) {
      if (!/^[A-Za-z0-9_.-]+\.lib$/i.test(name)) {continue;}
      const file = path.join(root, name), key = name.toLowerCase(), previous = imports.get(key);
      if (previous && fileHash(previous) !== fileHash(file)) {throw new Error("Conflicting Windows JIT OS library aliases: " + name);}
      if (!previous) {imports.set(key, file); inputs.push(file);}
    }
  }
  const fingerprints = buildFileInputs(inputs);
  fs.mkdirSync(output, {mode: 0o700}); fs.mkdirSync(plan.aliases); fs.mkdirSync(plan.libraries);
  for (const name of ["llvm-lib", "llvm-ranlib"]) {fs.symlinkSync(path.join(sdk, "bin/llvm-ar"), path.join(plan.aliases, name));}
  for (const [name, file] of imports) {fs.symlinkSync(file, path.join(plan.libraries, name));}
  // Physical dependency names let the compiler producer freeze actual SDK bytes, without
  // treating virtual /mom-sdk paths as unrecorded host files.
  fs.writeFileSync(plan.overlay, JSON.stringify({version: 0, "case-sensitive": false, "use-external-names": true,
    roots: virtual.map(([name, file]) => ({type: "file", name, "external-contents": file}))}), {flag: "wx"});
  fs.writeFileSync(plan.sourceOptionsFile, plan.sourceOptionsText, {flag: "wx"});
  if (plan.ruleOverride && plan.ruleOverrideText) {fs.writeFileSync(plan.ruleOverride, plan.ruleOverrideText, {flag: "wx"});}
  const toolchain = path.join(output, "toolchain.cmake"); fs.writeFileSync(toolchain, plan.toolchain, {flag: "wx"});
  const result = {version: 1, toolchain, inputs: {...fingerprints, ...(plan.ruleOverride ? {[plan.ruleOverride]: fileHash(plan.ruleOverride)} : {}),
    [toolchain]: fileHash(toolchain), [plan.overlay]: fileHash(plan.overlay), [plan.sourceOptionsFile]: fileHash(plan.sourceOptionsFile)},
  buildOnly: true, compiled: false, executed: false, publicationQualified: false};
  fs.writeFileSync(path.join(output, "result.json"), JSON.stringify(result, null, 2) + "\n", {flag: "wx"});
  return result;
}

module.exports = {heatUtilsSourceOptions, windowsIntelRuleOverride, validateWindowsJitDescriptor, windowsJitToolchainPlan, prepareWindowsJitToolchain};
if (require.main === module) {
  try {
    const [descriptor, sdk, nativeTools, output, cc, cxx, extra] = process.argv.slice(2);
    if (!descriptor || !sdk || !nativeTools || !output || extra || Boolean(cc) !== Boolean(cxx)) {
      throw new Error("Usage: prepare-native-jit-toolchain.js /windows-descriptor.json /DPC++ /native-generators /new/output [host-cc host-cxx]");
    }
    prepareWindowsJitToolchain(descriptor, sdk, nativeTools, output, process.env, cc && cxx ? {cc, cxx} : undefined);
  } catch (error) {console.error(error instanceof Error ? error.message : "Windows JIT toolchain preparation failed"); process.exitCode = 1;}
}
